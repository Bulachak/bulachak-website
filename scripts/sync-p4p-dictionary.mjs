// Copies the P4P Parafencing Dictionary entries from the canonical source (parafencing-project) into
// src/content/p4p-dictionary and regenerates entries.generated.ts, which the page imports.
// Usage: node scripts/sync-p4p-dictionary.mjs [path to .../src/pilot/dictionary/entries]
// Without a path it only regenerates entries.generated.ts from the Markdown files already here.
import { execFileSync } from 'node:child_process';
import { copyFileSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const to = path.join(process.cwd(), 'src/content/p4p-dictionary');
const from = process.argv[2];
if (from) {
  for (const name of readdirSync(to)) if (name.endsWith('.md')) rmSync(path.join(to, name));
  for (const name of readdirSync(from).filter((item) => item.endsWith('.md'))) {
    copyFileSync(path.join(from, name), path.join(to, name));
  }
}
const files = readdirSync(to)
  .filter((name) => name.endsWith('.md'))
  .sort()
  .map((name) => ({ name, raw: readFileSync(path.join(to, name), 'utf8').replace(/\r\n/g, '\n') }));
const body = `// Generated by scripts/sync-p4p-dictionary.mjs from the Markdown files in this folder. Do not edit.\nexport const dictionaryFiles: { name: string; raw: string }[] = ${JSON.stringify(files, null, 2)};\n`;
const out = path.join(to, 'entries.generated.ts');
writeFileSync(out, body);
execFileSync('npx', ['biome', 'format', '--write', out], { stdio: 'ignore', shell: true });
// biome-ignore lint/suspicious/noConsole: command-line script output.
console.log(`Wrote ${files.length} entry files into entries.generated.ts.`);
