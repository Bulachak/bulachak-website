function story(paragraphs: [string, string, string, string]): CaseCopy['sections'] {
  return [
    { id: 'challenge', title: 'Задача', paragraphs: [paragraphs[0]] },
    { id: 'approach', title: 'Мой подход', paragraphs: [paragraphs[1]] },
    { id: 'delivery', title: 'Что сделано', paragraphs: [paragraphs[2]] },
    { id: 'learning', title: 'Почему это важно', paragraphs: [paragraphs[3]] },
  ];
}

function translatedLinks(slug: string, labels: string[]): CaseCopy['links'] {
  const item = caseStudies.find((entry) => entry.slug === slug);
  if (!item || item.links.length !== labels.length) {
    throw new Error(`Russian link translations are incomplete for ${slug}`);
  }
  return item.links.map((link, index) => {
    const label = labels[index];
    if (label === undefined) {
      throw new Error(`Russian link label ${index} is missing for ${slug}`);
    }
    return { ...link, label };
  });
}

